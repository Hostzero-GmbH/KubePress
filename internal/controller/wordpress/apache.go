package wordpress

import (
	"fmt"

	crmv1 "hostzero.de/m/v2/api/v1"
	"k8s.io/apimachinery/pkg/api/resource"
)

const (
	// ApacheConfigKey is the ConfigMap key holding the generated prefork config
	ApacheConfigKey = "mpm_prefork.conf"
	// ApacheConfigMountPath is loaded by apache2.conf after mods-enabled, so
	// its directives override the image defaults from mpm_prefork.conf
	ApacheConfigMountPath = "/etc/apache2/conf-enabled/zz-kubepress-prefork.conf"

	// Memory budget per prefork worker. Workers share opcache and libraries,
	// the private part of a mod_php worker serving WordPress is ~15-40MB.
	apacheWorkerMemoryMiB = 50
	// Memory kept free of workers: parent process, opcache shared memory
	// (128MB), page cache headroom
	apacheReservedMemoryMiB = 256
	// Upper bound of workers per CPU core; mod_php workers are mostly
	// I/O bound, beyond this they only compete for the CPU quota
	apacheWorkersPerCPU = 16
	apacheMinWorkers    = 4
	apacheMaxWorkers    = 150
)

// ApachePreforkSettings holds the mpm_prefork directives derived from the
// container resources
type ApachePreforkSettings struct {
	MaxRequestWorkers int
	StartServers      int
	MinSpareServers   int
	MaxSpareServers   int
}

// ComputeApachePreforkSettings sizes the prefork MPM from the WordPress
// container's memory and CPU limits.
//
// The image default (StartServers 5, MaxRequestWorkers 150) has two
// problems: a burst of parallel requests (wp-admin, the site editor loads
// ~50 assets at once) has to wait for prefork's exponential spawn ramp,
// so even static files stall for seconds; and 150 workers would need
// several times the memory limit, so a real spike OOM-kills the pod
// instead of queueing.
func ComputeApachePreforkSettings(memoryLimit, cpuLimit string) (ApachePreforkSettings, error) {
	mem, err := resource.ParseQuantity(memoryLimit)
	if err != nil {
		return ApachePreforkSettings{}, fmt.Errorf("invalid memory limit %q: %w", memoryLimit, err)
	}
	cpu, err := resource.ParseQuantity(cpuLimit)
	if err != nil {
		return ApachePreforkSettings{}, fmt.Errorf("invalid cpu limit %q: %w", cpuLimit, err)
	}

	memMiB := int(mem.Value() / (1024 * 1024))
	byMemory := (memMiB - apacheReservedMemoryMiB) / apacheWorkerMemoryMiB
	byCPU := int(cpu.MilliValue()) * apacheWorkersPerCPU / 1000

	workers := min(byMemory, byCPU)
	workers = max(workers, apacheMinWorkers)
	workers = min(workers, apacheMaxWorkers)

	// Keep enough idle workers to absorb a burst without waiting for
	// prefork to fork its way up (it spawns 1, 2, 4, 8... per second).
	minSpare := max(workers/2, 2)
	maxSpare := max(workers*3/4, minSpare+1)

	return ApachePreforkSettings{
		MaxRequestWorkers: workers,
		StartServers:      minSpare,
		MinSpareServers:   minSpare,
		MaxSpareServers:   maxSpare,
	}, nil
}

// ApachePreforkConfig renders the prefork config file for a site
func ApachePreforkConfig(wp *crmv1.WordPressSite) (string, error) {
	s, err := ComputeApachePreforkSettings(wp.Spec.WordPress.Resources.MemoryLimit, wp.Spec.WordPress.Resources.CPULimit)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf(`# Generated by kubepress from the container resources, do not edit
<IfModule mpm_prefork_module>
	StartServers            %d
	MinSpareServers         %d
	MaxSpareServers         %d
	MaxRequestWorkers       %d
	MaxConnectionsPerChild  1000
</IfModule>
`, s.StartServers, s.MinSpareServers, s.MaxSpareServers, s.MaxRequestWorkers), nil
}
